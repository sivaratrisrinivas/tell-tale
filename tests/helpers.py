from __future__ import annotations

import json
import random
from pathlib import Path
from types import SimpleNamespace

import pandas as pd

REPOS = ["golang/go", "python/cpython", "rust-lang/rust", "swiftlang/swift", "vuejs/core", "mdn/content"]

HUMAN_SNIPPETS = [
    "go build fails on arm64 with linker error, saw it after upgrading to 1.16. repro below",
    "segfault in json decoder when the input has a trailing comma. tried on 3.9.1 and master",
    "rustc ICE when using const generics in a trait impl, backtrace attached. nightly-2021-03-02",
    "typo in the docs for Array.prototype.flat, the example output is wrong i think",
    "swift compiler crashes on this snippet, xcode 12.4, not sure if known. minimal repro:",
    "the test is flaky on windows, fails maybe 1 in 20 runs, looks like a timing thing",
    "hm, this regressed between 1.15 and 1.16 afaict. bisected to the scheduler change",
    "small fix: the error message said 'recieve', fixed spelling and added a test case",
]
WORDS = ("the a it this when we i you to of and in on for with but so then also fix bug crash test docs "
         "error build run fails works line file version os linux mac windows patch commit").split()
MACHINE_WORDS = ("comprehensive robust enhance ensure seamless streamline leverage improve maintainability "
                 "readability consistency overall significantly additionally furthermore").split()


def human_body(rng: random.Random, n: int) -> str:
    s = rng.choice(HUMAN_SNIPPETS) + ". " + " ".join(rng.choice(WORDS) for _ in range(n))
    if rng.random() < 0.3:
        s = "### What version are you using?\n1.16\n\n### What did you do?\n" + s + "\n\n### What did you expect?\nno crash"
    if rng.random() < 0.2:
        s += "\n\n```\npanic: runtime error: index out of range [3] with length 3\n```"
    return s


def machine_body(rng: random.Random, n: int) -> str:
    return ("## Summary\n\nThis change will " + " ".join(rng.choice(MACHINE_WORDS + WORDS) for _ in range(n))
            + ".\n\n## Changes\n- Enhance robustness\n- Ensure consistency\n\n## Testing\nAll tests pass.")


def make_issue_tables(root: Path, per_repo: int = 260, seed: int = 0) -> Path:
    """Write data/issues/{owner}/{repo}/0.parquet (+ comments, timeline_events) like open-github-issues."""
    rng = random.Random(seed)
    for repo in REPOS:
        rows = []
        for i in range(per_repo):
            year = 2016 + i % 10        # 2016..2025: some post-cutoff rows
            author = rng.choice(["alice", "bob", "carol", "dave", "erin"]) + str(i % 37)
            if i % 25 == 0:
                author = "dependabot[bot]"
            if i % 31 == 0:
                author = "robot-ci-1"
            n = 8 if i % 17 == 0 else rng.randint(30, 160)   # some too short
            body = human_body(rng, n) if year < 2023 else machine_body(rng, n)
            rows.append({"number": i + 1, "is_pull_request": bool(i % 2), "title": f"{'cmd/go' if i % 3 else 'docs'}: issue {i}",
                         "body": body, "author": author, "created_at": pd.Timestamp(f"{year}-0{1 + i % 9}-15T10:00:00"),
                         "labels": json.dumps(["bug"] if i % 4 == 0 else []),
                         "state": "closed" if i % 3 else "open", "closed_at": pd.Timestamp(f"{year}-12-01")})
        # an exact duplicate and a near duplicate
        dup = dict(rows[5]); dup["number"] = 9001; rows.append(dup)
        near = dict(rows[7]); near["number"] = 9002; near["body"] = rows[7]["body"] + " thanks"; rows.append(near)
        p = root / "data" / "issues" / repo / "0.parquet"
        p.parent.mkdir(parents=True, exist_ok=True)
        pd.DataFrame(rows).to_parquet(p, index=False)
        com = [{"issue_number": r["number"], "body": "Closing: this looks like AI slop generated by an LLM.",
                "author_association": "MEMBER"} for r in rows if r["created_at"].year >= 2025 and r["number"] % 3]
        cp = root / "data" / "comments" / repo / "0.parquet"
        cp.parent.mkdir(parents=True, exist_ok=True)
        pd.DataFrame(com or [{"issue_number": -1, "body": "", "author_association": "NONE"}]).to_parquet(cp, index=False)
        tp = root / "data" / "timeline_events" / repo / "0.parquet"
        tp.parent.mkdir(parents=True, exist_ok=True)
        pd.DataFrame([{"issue_number": -1, "event_type": "labeled", "label_name": "x"}]).to_parquet(tp, index=False)
    return root


class FakeBackend:
    """Mimics the OpenAI client response objects. Counts calls."""

    def __init__(self, fail_first: int = 0):
        self.calls = 0
        self.fail_first = fail_first
        self.models: list[str] = []

    def create(self, *, model, messages, **params):
        self.calls += 1
        if self.calls <= self.fail_first:
            err = RuntimeError("rate limited")
            err.status_code = 429
            raise err
        self.models.append(model)
        prompt = messages[0]["content"]
        rng = random.Random(prompt)
        if "state what this" in prompt:
            text = "A crash in the parser when input has a trailing comma, reported on Linux with version 1.16."
        elif prompt.startswith("Fix grammar"):
            text = prompt.split("\n\n", 1)[1]
        elif prompt.startswith("Reply with"):
            text = "ok"
        else:
            words = int(prompt.split("about ")[-1].split(" words")[0]) if "about " in prompt else 80
            text = "Enhance parser robustness for trailing commas\n\n" + machine_body(rng, max(10, words - 25))
        usage = SimpleNamespace(prompt_tokens=len(prompt) // 4, completion_tokens=len(text) // 4,
                                completion_tokens_details=SimpleNamespace(reasoning_tokens=7))
        msg = SimpleNamespace(content=text)
        return SimpleNamespace(choices=[SimpleNamespace(message=msg, finish_reason="stop")], usage=usage)


def make_tiny_base(out: Path, corpus: list[str]) -> Path:
    """A ~100K-param ModernBERT + a WordPiece tokenizer trained on `corpus`, saved like a Hub model."""
    from tokenizers import Tokenizer, models, normalizers, pre_tokenizers, processors, trainers
    from transformers import ModernBertConfig, ModernBertModel, PreTrainedTokenizerFast

    tk = Tokenizer(models.WordPiece(unk_token="[UNK]"))
    tk.normalizer = normalizers.Lowercase()
    tk.pre_tokenizer = pre_tokenizers.BertPreTokenizer()
    tk.train_from_iterator(corpus, trainers.WordPieceTrainer(vocab_size=600, special_tokens=[
        "[PAD]", "[UNK]", "[CLS]", "[SEP]", "[MASK]"]))
    tk.post_processor = processors.TemplateProcessing(single="[CLS] $A [SEP]", special_tokens=[
        ("[CLS]", tk.token_to_id("[CLS]")), ("[SEP]", tk.token_to_id("[SEP]"))])
    tok = PreTrainedTokenizerFast(tokenizer_object=tk, pad_token="[PAD]", unk_token="[UNK]", cls_token="[CLS]",
                                  sep_token="[SEP]", mask_token="[MASK]")
    cfg = ModernBertConfig(vocab_size=tk.get_vocab_size(), hidden_size=32, intermediate_size=64, num_hidden_layers=2,
                           num_attention_heads=2, max_position_embeddings=1024, pad_token_id=tk.token_to_id("[PAD]"),
                           cls_token_id=tk.token_to_id("[CLS]"), sep_token_id=tk.token_to_id("[SEP]"),
                           bos_token_id=tk.token_to_id("[CLS]"), eos_token_id=tk.token_to_id("[SEP]"),
                           local_attention=64, global_attn_every_n_layers=2)
    out.mkdir(parents=True, exist_ok=True)
    ModernBertModel(cfg).save_pretrained(out)
    tok.save_pretrained(out)
    return out
