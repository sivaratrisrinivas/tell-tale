"""T6 candidate finder: 2025+ PRs/issues closed after an AI-related comment or label.

Output is a CSV for the owner to hand-check (fill the `verdict` column with
`slop`, `human` or `unsure`). This set is NEVER used for training.

Note: in open-index/open-github-issues the `comments` table is only populated
for some repos (of the six spec repos: mdn/content and vuejs/core). Labels
come from `timeline_events` (LabeledEvent / labeled).
"""
from __future__ import annotations

import re
from pathlib import Path

import pandas as pd

from ..config import load_yaml
from .extract import ISSUE_COLS, bot_regex, clean_items, download_table, repo_file

KEYWORDS = re.compile(r"\b(?:ai[- ]generated|ai slop|slop|llm|chatgpt|copilot|generated by|"
                      r"machine[- ]generated|written by (?:an? )?ai|claude|gemini|\bai\b)", re.I)


def find_candidates(cfg_path: str = "data.yaml", since: str = "2025-01-01", local_dir: str | None = None,
                    out_csv: str = "runs/data/t6_candidates.csv", max_rows: int = 600) -> pd.DataFrame:
    cfg = load_yaml(cfg_path)
    bots = bot_regex(cfg["bot_patterns"])
    rows = []
    for repo in cfg["repos"]:
        def path(table: str) -> Path:
            return Path(local_dir) / repo_file(table, repo) if local_dir else download_table(
                table, repo, cfg["source_dataset"])

        issues = pd.read_parquet(path("issues"), columns=ISSUE_COLS + ["state", "closed_at"])
        items = clean_items(issues, repo, cutoff=since, min_words=cfg["min_body_words"], bots=bots, before=False)
        closed = issues.set_index("number")["state"].eq("closed")
        items = items[items["id"].str.split("#").str[1].astype(int).map(closed).fillna(False)]
        nums = set(items["id"].str.split("#").str[1].astype(int))
        hits: dict[int, str] = {}
        try:
            com = pd.read_parquet(path("comments"), columns=["issue_number", "body", "author_association"])
            com = com[com["issue_number"].isin(nums)]
            com = com[com["author_association"].isin(["OWNER", "MEMBER", "COLLABORATOR"])]
            m = com[com["body"].fillna("").str.contains(KEYWORDS)]
            for n, b in zip(m["issue_number"], m["body"]):
                hits.setdefault(int(n), "comment: " + b[:300].replace("\n", " "))
        except Exception as exc:  # noqa: BLE001 — some repos have no comments table
            print(f"{repo}: no comments ({type(exc).__name__})")
        try:
            tl = pd.read_parquet(path("timeline_events"), columns=["issue_number", "event_type", "label_name"])
            tl = tl[tl["issue_number"].isin(nums) & tl["label_name"].fillna("").str.contains(KEYWORDS)]
            for n, lab in zip(tl["issue_number"], tl["label_name"]):
                hits.setdefault(int(n), f"label: {lab}")
        except Exception as exc:  # noqa: BLE001
            print(f"{repo}: no timeline ({type(exc).__name__})")
        sel = items[items["id"].str.split("#").str[1].astype(int).isin(hits)]
        for _, r in sel.iterrows():
            n = int(r["id"].split("#")[1])
            path_kind = "pull" if r["kind"] == "pr" else "issues"
            rows.append({**r[["id", "repo", "kind", "created_at", "title", "body"]].to_dict(),
                         "url": f"https://github.com/{repo}/{path_kind}/{n}", "evidence": hits[n], "verdict": ""})
        print(f"{repo}: {len(sel)} candidates")
    df = pd.DataFrame(rows).head(max_rows)
    Path(out_csv).parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(out_csv, index=False)
    return df
